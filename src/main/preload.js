  setSessionOptions: invoke('session:setOptions'),
  baseline: invoke('session:baseline'),
  revertFile: invoke('session:revert'),
  compact: invoke('session:compact'),
  exportSession: invoke('session:export'),
  send: invoke('agent:send'),
  stop: invoke('agent:stop'),
  permission: invoke('agent:permission'),
  rewind: invoke('agent:rewind'),
  procList: invoke('proc:list'),
  procStop: invoke('proc:stop'),
