const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch) => (...args) => ipcRenderer.invoke(ch, ...args);
const on = (ch) => (cb) => { const h = (_e, ev) => cb(ev); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); };

